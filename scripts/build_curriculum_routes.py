def expected_weeks(grade: int) -> int:
    return 33 if grade == 1 else 34


def subject_title(subject: str, grade: int) -> str:
    if subject == "math":
        return f"Математика, {grade} класс: годовой маршрут Kidion"
    return f"Русский язык, {grade} класс: годовой маршрут Kidion"


def mission_title(subject: str, week: int, theme: str) -> str:
    if subject == "math":
        return f"Миссия {week}: математический ключ - {theme}"
    return f"Миссия {week}: языковой артефакт - {theme}"


def mission_goal(subject: str, theme: str) -> str:
    if subject == "math":
        return f"Открыть новый участок карты, решая школьные задания по теме «{theme}»."
    return f"Собрать страницу языковой карты, применяя правила по теме «{theme}»."


def skills_for(subject: str, theme: str) -> list[str]:
    if subject == "math":
        return [
            f"объяснять школьную тему «{theme}» простыми словами",
            f"решать короткие задания по теме «{theme}»",
            "проверять ответ и выбирать способ решения",
        ]
    return [
        f"узнавать языковое явление «{theme}»",
        f"применять правило по теме «{theme}» в словах, предложениях или тексте",
        "проверять написанное и объяснять выбор",
    ]


def lesson_title(step_label: str, theme: str) -> str:
    return f"{step_label}: {theme}"


def build_lesson(subject: str, theme: str, order: int, role: str, label: str, focus: str, hint: str) -> dict:
    subject_action = "решения" if subject == "math" else "языкового выбора"
    return {
        "order": order,
        "role": role,
        "title": lesson_title(label, theme),
        "school_focus": f"{focus}: «{theme}»",
        "prompt_hint": f"{hint} Обязательно удерживай школьный фокус «{theme}» и проси ребенка объяснять ход {subject_action}.",
    }


def build_route(subject: str, grade: int, themes: list[str]) -> dict:
    expected = expected_weeks(grade)
    if len(themes) != expected:
        raise ValueError(f"{subject} grade {grade}: expected {expected} themes, got {len(themes)}")

    source_key = "primary" if grade <= 4 else "middle"
    blocks = []
    for week, theme in enumerate(themes, start=1):
        blocks.append(
            {
                "week": week,
                "school_theme": theme,
                "skills": skills_for(subject, theme),
                "mission_title": mission_title(subject, week, theme),
                "mission_goal": mission_goal(subject, theme),
                "lessons": [
                    build_lesson(subject, theme, order, role, label, focus, hint)
                    for order, (role, label, focus, hint) in enumerate(LESSON_STEPS, start=1)
                ],
            }
        )

    return {
        "subject": subject,
        "grade": grade,
        "title": subject_title(subject, grade),
        "source_basis": [SOURCE_BASIS[subject][source_key]],
        "blocks": blocks,
    }


def main() -> None:
    ROUTES_DIR.mkdir(parents=True, exist_ok=True)
    expected_files = set()

    for subject, grades in CURRICULUM_THEMES.items():
        for grade, themes in grades.items():
            route = build_route(subject, grade, themes)
            path = ROUTES_DIR / f"{subject}_{grade}.json"
            path.write_text(
                json.dumps(route, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            expected_files.add(path.name)

    for path in ROUTES_DIR.glob("*.json"):
        if path.name not in expected_files:
            path.unlink()


if __name__ == "__main__":
    main()
