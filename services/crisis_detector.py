"""
crisis_detector.py — Detect crisis topics in children's messages.

When a child mentions suicide, self-harm, abuse, bullying, or danger,
we skip the AI call entirely and return a safe, empathetic template response.
"""

import re

# Helpline info
_HELPLINE = "8-800-2000-122"  # Детский телефон доверия (free, 24/7)
_HELPLINE_TEXT = f"Детский телефон доверия: {_HELPLINE} (бесплатно, круглосуточно)"


# --- Crisis categories with patterns and responses ---

class CrisisCategory:
    def __init__(self, name: str, patterns: list[str], response: str):
        self.name = name
        self.patterns = [re.compile(p, re.IGNORECASE) for p in patterns]
        self.response = response


CRISIS_CATEGORIES = [
    CrisisCategory(
        name="self_harm",
        patterns=[
            r'хочу\s+умереть',
            r'не\s+хочу\s+жить',
            r'лучше\s+бы\s+меня\s+не\s+было',
            r'хочу\s+(?:убить|покончить)\s+(?:с\s+)?собой',
            r'(?:режу|порежу|порезал[аи]?)\s+себ[яе]',
            r'(?:хочу|буду)\s+(?:резать|порезать)',
            r'наглотаюсь\s+таблеток',
            r'(?:выпрыгну|спрыгну|прыгну)\s+(?:из|с|в)',
            r'повешусь|повеш[уа]',
            r'убью\s+себя',
            r'покончу\s+с\s+собой',
            r'суицид',
            r'самоубийств',
        ],
        response=(
            "Мне очень важно то, что ты сейчас чувствуешь. "
            "Пожалуйста, поговори с кем-то из взрослых, кому доверяешь -- "
            "с мамой, папой, учителем или другим близким человеком. "
            "Они обязательно помогут.\n\n"
            f"Ты также можешь позвонить: {_HELPLINE_TEXT}. "
            "Там ответят добрые люди, которые выслушают тебя."
        ),
    ),
    CrisisCategory(
        name="abuse",
        patterns=[
            r'меня\s+(?:бьют|бьёт|ударил[аи]?|побил[аи]?)',
            r'(?:папа|мама|отец|отчим|мачеха|дедушка|бабушка|дядя|тётя|брат|сестра)\s+(?:бьёт|бьют|ударил|побил)',
            r'ко\s+мне\s+(?:пристают|пристаёт|лезут|лезет|трогают)',
            r'(?:трогают|трогает|лапает)\s+(?:меня|мои)',
            r'боюсь\s+идти\s+домой',
            r'меня\s+(?:насилу|заставля)',
            r'меня\s+(?:раздевают|раздевает|заставляют\s+раздеться)',
            r'(?:нельзя|запрещают)\s+(?:рассказывать|говорить)',
            r'(?:это\s+)?(?:наш|секрет).{0,20}(?:никому|не\s+говори)',
        ],
        response=(
            "Я слышу тебя, и мне очень жаль, что тебе приходится через это проходить. "
            "То, что происходит -- это НЕ твоя вина.\n\n"
            "Пожалуйста, расскажи об этом взрослому, которому доверяешь: "
            "учителю, школьному психологу, родственнику или другому человеку, "
            "который может помочь.\n\n"
            f"Ты можешь позвонить: {_HELPLINE_TEXT}. "
            "Там помогут и всё будет в секрете."
        ),
    ),
    CrisisCategory(
        name="bullying",
        patterns=[
            r'меня\s+(?:травят|обижают|унижают|дразнят|обзывают)',
            r'(?:травят|издеваются|смеются)\s+(?:в\s+)?(?:школе|классе|на\s+улице)',
            r'(?:никто\s+)?не\s+(?:хочет|хотят)\s+(?:со\s+мной\s+)?дружить',
            r'все\s+(?:против\s+меня|меня\s+ненавидят)',
            r'(?:бьют|толкают|пинают)\s+(?:в\s+)?(?:школе|классе)',
            r'забирают\s+(?:мои|у\s+меня)\s+вещи',
            r'угрожают\s+мне',
        ],
        response=(
            "Мне очень грустно это слышать. То, что с тобой происходит -- это несправедливо, "
            "и ты не заслуживаешь такого отношения.\n\n"
            "Самое важное сейчас -- рассказать об этом взрослому: "
            "маме, папе, учителю или школьному психологу. Они смогут помочь.\n\n"
            f"Ещё ты можешь позвонить: {_HELPLINE_TEXT}."
        ),
    ),
    CrisisCategory(
        name="danger_to_others",
        patterns=[
            r'хочу\s+(?:убить|отомстить|взорвать|поджечь|отравить)',
            r'(?:сделаю|сделать)\s+(?:бомбу|взрывчатку|оружие)',
            r'(?:принесу|возьму)\s+(?:нож|оружие|пистолет)\s+(?:в\s+)?школу',
            r'все\s+пожалеют',
            r'(?:расстреляю|перестреляю|зарежу)',
        ],
        response=(
            "Я понимаю, что тебе сейчас очень тяжело и ты злишься. "
            "Эти чувства бывают у всех, и это нормально.\n\n"
            "Но пожалуйста, поговори с кем-то из взрослых о том, что ты чувствуешь. "
            "Мама, папа, учитель или психолог помогут тебе справиться.\n\n"
            f"Позвони: {_HELPLINE_TEXT}."
        ),
    ),
    CrisisCategory(
        name="substances",
        patterns=[
            r'где\s+(?:купить|достать|взять)\s+(?:наркотик|наркотики|травку|марихуану|спайс|соль|мефедрон|амфетамин|экстази|героин|кокаин)',
            r'(?:как|хочу)\s+(?:попробовать|употреб|курить|нюхать)\s+(?:наркотик|травку)',
            r'(?:как|где)\s+(?:купить|достать)\s+(?:алкоголь|водку|пиво|вино|сигареты|вейп)',
            r'(?:пью|выпиваю|напиваюсь)',
        ],
        response=(
            "Это очень опасная тема, и я не могу помогать с этим. "
            "Наркотики и алкоголь очень вредны, особенно для растущего организма.\n\n"
            "Если тебе кто-то предлагает попробовать -- скажи нет и расскажи об этом взрослому.\n\n"
            f"Если тебе нужна помощь: {_HELPLINE_TEXT}."
        ),
    ),
    CrisisCategory(
        name="runaway",
        patterns=[
            r'хочу\s+(?:сбежать|убежать)\s+(?:из\s+дома|от\s+родителей)',
            r'убегу\s+из\s+дома',
            r'(?:уйду|уеду)\s+(?:из\s+дома|навсегда)',
        ],
        response=(
            "Я понимаю, что тебе сейчас тяжело дома. "
            "Но уходить одному -- опасно.\n\n"
            "Поговори с кем-то из взрослых, кому доверяешь: "
            "учителем, родственником, другом семьи.\n\n"
            f"Или позвони: {_HELPLINE_TEXT}. "
            "Там выслушают и помогут разобраться."
        ),
    ),
]


def detect_crisis(text: str) -> tuple[str | None, str | None]:
    """
    Check if text contains a crisis topic.

    Returns:
        (category_name, safe_response) if crisis detected
        (None, None) if no crisis
    """
    if not text:
        return None, None

    for category in CRISIS_CATEGORIES:
        for pattern in category.patterns:
            if pattern.search(text):
                return category.name, category.response

    return None, None
